FIRST = 0x20
LAST = 0x7E
HEIGHT = 8
COLS = 6          # 5 列字形 + 1 列间距


def build_table():
    """返回 95 个字符 x 6 列的二维列表，超出范围的字符用空格顶上。"""
    table = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        cols5 = FONT.get(ch)
        if cols5 is None:
            raise SystemExit(f'字模缺少字符 {ch!r} (0x{code:02X})')
        if len(cols5) != 5:
            raise SystemExit(f'字符 {ch!r} 的列数不是 5')
        for v in cols5:
            if not (0 <= v <= 0x7F):
                raise SystemExit(f'字符 {ch!r} 的列值 0x{v:02X} 超出一列 7 行的范围')
        table.append(list(cols5) + [0x00])
    return table


def emit_c(table, path):
    lines = []
    lines.append('/* bsp_font6x8.c - 6x8 点阵 ASCII 字模（本项目自行制作）')
    lines.append(' *')
    lines.append(' * 本文件由 tools/make_font6x8.py 生成，不要手改；')
    lines.append(' * 要调整字形请改脚本里的 FONT 表，然后重新生成并看预览图。')
    lines.append(' *')
    lines.append(' * 表结构：95 个字符（0x20 ~ 0x7E）x 6 列，按列取模，bit0 在最上面。')
    lines.append(' */')
    lines.append('')
    lines.append('#include "bsp_font6x8.h"')
    lines.append('')
    lines.append('const uint8_t Font6x8[FONT6X8_CHAR_COUNT][8] =')
    lines.append('{')
    for i, cols in enumerate(table):
        ch = chr(FIRST + i)
        # 字符本身放进注释，方便人工核对时定位
        if ch == '\\':
            label = '\\\\'
        elif ch == "'":
            label = "\\'"
        else:
            label = ch
        shown = f"'{label}'" if ch != ' ' else "' ' (space)"
        body = ', '.join(f'0x{v:02X}' for v in cols)
        lines.append(f'\t{{ {body} }},   /* 0x{FIRST + i:02X}  {shown} */')
    lines.append('};')
    lines.append('')
    lines.append('const uint8_t *Font6x8_GetGlyph(char c)')
    lines.append('{')
    lines.append('\tuint8_t code = (uint8_t)c;')
    lines.append('')
    lines.append('\t/* 超出可打印范围的字符（含中文的多字节）统一按空格画，')
    lines.append('\t * 调用方不用自己判范围 */')
    lines.append('\tif((code < FONT6X8_FIRST_CHAR) || (code > FONT6X8_LAST_CHAR))')
    lines.append('\t{')
    lines.append('\t\tcode = (uint8_t)\' \';')
    lines.append('\t}')
    lines.append('')
    lines.append('\treturn Font6x8[(uint8_t)(code - FONT6X8_FIRST_CHAR)];')
    lines.append('}')
    lines.append('')

    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'已生成 {path}')


def emit_preview(table, path, scale=12):
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        print('没有 Pillow，跳过预览图')
        return

    # 每行 16 个字符，方便一眼扫完
    per_row = 16
    rows = (len(table) + per_row - 1) // per_row
    cw, chh = COLS * scale, HEIGHT * scale
    pad = 4 * scale
    img = Image.new('RGB', (per_row * cw + pad, rows * chh + pad), 'white')
    d = ImageDraw.Draw(img)

    for i, cols in enumerate(table):
        gx = (i % per_row) * cw + pad // 2
        gy = (i // per_row) * chh + pad // 2
        for col in range(COLS):
            bits = cols[col]
            for row in range(HEIGHT):
                if bits & (1 << row):
                    x0 = gx + col * scale
                    y0 = gy + row * scale
                    d.rectangle([x0, y0, x0 + scale - 1, y0 + scale - 1], fill='black')

    img.save(path)
    print(f'已生成预览图 {path}（{img.width}x{img.height}）')


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    table = build_table()

    emit_c(table, os.path.join(root, 'bsp', 'bsp_font6x8.c'))

    build_dir = os.path.join(root, 'build')
    os.makedirs(build_dir, exist_ok=True)
    emit_preview(table, os.path.join(build_dir, 'font6x8_preview.png'))

    print(f'共 {len(table)} 个字符 x {COLS} 列 x {HEIGHT} 行')


if __name__ == '__main__':
    main()
